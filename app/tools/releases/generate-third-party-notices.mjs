import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const appRoot = path.resolve(import.meta.dirname, "../..");
const repositoryRoot = path.resolve(appRoot, "..");
const lockPath = path.join(appRoot, "package-lock.json");
const outputPath = path.join(
  repositoryRoot,
  "THIRD_PARTY_LICENSES",
  "npm-production-notices.txt",
);
const lockText = await readFile(lockPath, "utf8");
const lock = JSON.parse(lockText);
const includedBuildPackages = new Set(["node_modules/electron"]);

const packageEntries = Object.entries(lock.packages)
  .filter(
    ([relativePath, metadata]) =>
      relativePath.startsWith("node_modules/") &&
      (metadata.dev !== true || includedBuildPackages.has(relativePath)),
  )
  .sort(([leftPath, left], [rightPath, right]) => {
    const leftKey = `${left.name || leftPath}\0${left.version}\0${leftPath}`;
    const rightKey = `${right.name || rightPath}\0${right.version}\0${rightPath}`;
    return leftKey.localeCompare(rightKey);
  });

const sections = [];
for (const [relativePath, lockMetadata] of packageEntries) {
  const packageDirectory = path.join(appRoot, relativePath);
  const packageJson = JSON.parse(
    await readFile(path.join(packageDirectory, "package.json"), "utf8"),
  );
  const files = (await readdir(packageDirectory)).filter((name) =>
    /^(licen[sc]e|copying|notice)(\..*|$)/i.test(name),
  );
  if (files.length === 0) {
    throw new Error(
      `${packageJson.name}@${packageJson.version} has no installed license file.`,
    );
  }

  const licenseBlocks = [];
  for (const fileName of files.sort()) {
    const contents = await readFile(
      path.join(packageDirectory, fileName),
      "utf8",
    );
    licenseBlocks.push([`--- ${fileName} ---`, contents.trimEnd()].join("\n"));
  }

  sections.push(
    [
      "=".repeat(80),
      `${packageJson.name}@${packageJson.version}`,
      `Installed path: ${relativePath}`,
      `Declared license: ${
        typeof packageJson.license === "string"
          ? packageJson.license
          : JSON.stringify(
              packageJson.license || lockMetadata.license || "UNKNOWN",
            )
      }`,
      "-".repeat(80),
      licenseBlocks.join("\n\n"),
    ].join("\n"),
  );
}

const lockHash = createHash("sha256").update(lockText).digest("hex");
const output = [
  "CodexDesk production dependency notices",
  "",
  "Generated by app/tools/releases/generate-third-party-notices.mjs.",
  "Do not edit this file by hand.",
  `Source lockfile SHA-256: ${lockHash}`,
  `Included packages: ${packageEntries.length}`,
  "",
  "Packages reachable from app/package.json production dependencies are included.",
  "Electron is also included because its runtime is distributed with the app even",
  "though Electron is installed as a build dependency. Chromium's complete notices",
  "are packaged separately as LICENSES.chromium.html.",
  "",
  ...sections,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => null);
  if (current !== output) {
    throw new Error(
      "Production dependency notices are stale. Run npm run release:notices.",
    );
  }
  console.log(
    `Production dependency notices are current (${packageEntries.length} packages).`,
  );
} else {
  await writeFile(outputPath, output, "utf8");
  console.log(`Wrote ${outputPath} (${packageEntries.length} packages).`);
}
